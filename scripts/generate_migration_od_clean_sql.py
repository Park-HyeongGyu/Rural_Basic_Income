def quote_identifier(identifier: str) -> str:
    return '"' + identifier.replace('"', '""') + '"'


def clean_count_expr(value_expr: str) -> str:
    return (
        "coalesce(nullif(regexp_replace("
        f"{value_expr}, '[^0-9-]', '', 'g'), ''), '0')::bigint"
    )


def prepared_age_columns() -> str:
    return ",\n".join(
        f"        {clean_count_expr(f'raw_mo.{quote_identifier(column)}')} "
        f"AS {quote_identifier(column)}"
        for column in AGE_RAW_COLUMNS
    )


def canonical_age_sums() -> str:
    lines: list[str] = []
    for sex in ("male", "female"):
        for bucket in AGE_BUCKETS:
            source_columns = [
                f"SUM(st.{quote_identifier(age_raw_column(sex, age))})"
                for age in bucket.ages
            ]
            lines.append(
                "    ("
                + " + ".join(source_columns)
                + f")::bigint AS {quote_identifier(bucket_sql_column(sex, bucket))}"
            )
    return ",\n".join(lines)


def dimension_age_rows() -> str:
    rows: list[str] = []
    for bucket in AGE_BUCKETS:
        male_column = quote_identifier(bucket_sql_column("male", bucket))
        female_column = quote_identifier(bucket_sql_column("female", bucket))
        rows.append(
            "SELECT\n"
            "    date,\n"
            "    destination_sido,\n"
            "    destination_sigungu,\n"
            "    origin_sido,\n"
            "    origin_sigungu,\n"
            "    'all'::text AS sex,\n"
            f"    '{bucket.label}'::text AS age,\n"
            f"    ({male_column} + {female_column})::bigint AS move_count\n"
            "FROM migration_od_canonical"
        )
    return "\nUNION ALL\n".join(rows)


def dimension_sex_age_rows() -> str:
    rows: list[str] = []
    for sex, label in (("male", "male"), ("female", "female")):
        for bucket in AGE_BUCKETS:
            column = quote_identifier(bucket_sql_column(sex, bucket))
            rows.append(
                "SELECT\n"
                "    date,\n"
                "    destination_sido,\n"
                "    destination_sigungu,\n"
                "    origin_sido,\n"
                "    origin_sigungu,\n"
                f"    '{label}'::text AS sex,\n"
                f"    '{bucket.label}'::text AS age,\n"
                f"    {column} AS move_count\n"
                "FROM migration_od_canonical"
            )
    return "\nUNION ALL\n".join(rows)


